        // ===== S12 Haptics tab (plugin-tab mode) =====
        // One card per S12 firmware channel, generated by tools/rebuild_s12_cards.py.
        // Element names are S12{Cap}{Field}; handlers dispatch on Tag ("abs",
        // "abs:frequency"). Profile-tier — mutate PedalHapticsSettings and Save.

        private static readonly (string Tag, string Cap, PedalHapticsEffectSlot Slot)[] S12Channels =
        {
            ("tc", "Tc", PedalHapticsEffectSlot.TractionControl),
            ("abs", "Abs", PedalHapticsEffectSlot.Abs),
            ("lockup", "Lockup", PedalHapticsEffectSlot.Lockup),
            ("threshold", "Threshold", PedalHapticsEffectSlot.BrakeThreshold),
            ("engine", "Engine", PedalHapticsEffectSlot.EngineVibration),
            ("bite", "Bite", PedalHapticsEffectSlot.ClutchBitePoint),
            ("gear", "Gear", PedalHapticsEffectSlot.GearShift),
            ("slip", "Slip", PedalHapticsEffectSlot.WheelSlip),
            ("road", "Road", PedalHapticsEffectSlot.RoadTexture),
        };

        private bool _s12ScopeInitialized;

        // Shown only while the S12 is routed to the plugin tab and a unit has
        // answered; ShowAllTabs can still force it visible.
        private void RefreshPedalHapticsTab()
        {
            bool show = _plugin.PedalHapticsRoutedToPluginTab
                        && _plugin.PedalHapticsRegistry?.AnyDetected == true;
            PedalHapticsTab.Visibility = show ? Visibility.Visible : Visibility.Collapsed;
            if (!PedalHapticsTab.IsSelected) return;
            SeedPedalHapticsControls(_plugin.Settings?.ProfileStore?.CurrentProfile?.PedalHaptics);
        }

        private void SeedPedalHapticsControls(PedalHapticsSettings? settings)
        {
            if (!_s12ScopeInitialized)
            {
                _s12ScopeInitialized = true;
                S12Scope.Poll = () => _plugin.GetPedalHapticsScopeSamples();
            }

            settings ??= new PedalHapticsSettings();
            foreach (var (tag, cap, slot) in S12Channels)
            {
                var fx = settings.Get(slot);
                string p = "S12" + cap;
                bool road = slot == PedalHapticsEffectSlot.RoadTexture;

                S12Find<ToggleButton>(p + "Enable").IsChecked = fx.Enabled;
                S12Find<ToggleButton>(p + "Throttle").IsChecked = fx.Throttle;
                S12Find<ToggleButton>(p + "Brake").IsChecked = fx.Brake;
                S12Find<ToggleButton>(p + "Clutch").IsChecked = fx.Clutch;
                S12Find<Selector>(p + "TriggerMode").SelectedIndex = (int)fx.TriggerMode;
                SeedLfeTrigger(S12Find<TextBlock>(p + "TriggerText"), fx.TriggerFormula);

                if (road)
                    SeedS12Position(S12Find<TextBlock>(p + "FrequencyFormulaText"), fx);
                else
                {
                    SeedLfeParam(S12Find<Slider>(p + "FrequencySlider"), S12Find<TextBox>(p + "FrequencyValue"),
                                 S12Find<TextBlock>(p + "FrequencyFormulaText"), fx.Frequency, fx.FrequencyFormula);
                    SeedS12FreqLimits(p, fx);
                }
                SeedLfeParam(S12Find<Slider>(p + "Intensity"), S12Find<TextBox>(p + "IntensityValue"),
                             S12Find<TextBlock>(p + "IntensityFormulaText"), fx.Intensity, fx.IntensityFormula);
                SeedS12Edge(p, fx);
            }

            // Live formula readouts (seeding only runs while the tab is selected).
            foreach (var (_, cap, slot) in S12Channels)
            {
                var fx = settings.Get(slot);
                string p = "S12" + cap;
                UpdateLfeCalc(S12Find<TextBlock>(p + "TriggerCalc"), fx.TriggerFormula, r => r);
                Func<double, double> freqShape = slot == PedalHapticsEffectSlot.RoadTexture
                    ? (r => Math.Max(MozaPedalHapticsProtocol.MinRoadPosition, Math.Min(MozaPedalHapticsProtocol.MaxRoadPosition, r)))
                    : (Func<double, double>)fx.RescaleFreq;
                UpdateLfeCalc(S12Find<TextBlock>(p + "FrequencyCalc"), fx.FrequencyFormula, freqShape);
                UpdateLfeCalc(S12Find<TextBlock>(p + "IntensityCalc"), fx.IntensityFormula, r => Math.Max(0, Math.Min(100, r)));
            }
        }

        private T S12Find<T>(string name) where T : class
            => FindName(name) as T ?? throw new InvalidOperationException("S12 tab element missing: " + name);

        // Road Texture's position has no slider (a constant position settles to
        // silence); the line shows the formula, or the static value without one.
        private static void SeedS12Position(TextBlock text, PedalHapticsEffect fx)
        {
            bool has = !string.IsNullOrWhiteSpace(fx.FrequencyFormula);
            text.Visibility = Visibility.Visible;
            text.Text = has ? fx.FrequencyFormula : ((int)Math.Round(fx.Frequency)).ToString();
            text.ToolTip = has ? fx.FrequencyFormula : null;
        }

        private void SeedS12FreqLimits(string p, PedalHapticsEffect fx)
        {
            S12Find<FrameworkElement>(p + "FreqLimits").Visibility =
                string.IsNullOrWhiteSpace(fx.FrequencyFormula) ? Visibility.Collapsed : Visibility.Visible;
            double lo = ClampS12Hz(fx.FrequencyMin), hi = ClampS12Hz(fx.FrequencyMax);
            var range = S12Find<MozaControls.MozaRangeSlider>(p + "FreqRange");
            range.LowValue = lo;
            range.HighValue = hi;
            S12Find<TextBlock>(p + "FreqRangeText").Text = LfeRangeText(lo, hi);
        }

        private void SeedS12Edge(string p, PedalHapticsEffect fx)
        {
            S12Find<FrameworkElement>(p + "EdgeOptions").Visibility =
                fx.TriggerMode == BaseLfeTriggerMode.OnChange ? Visibility.Visible : Visibility.Collapsed;
            int pulse = ClampS12Pulse(fx.PulseMs);
            S12Find<Slider>(p + "PulseSlider").Value = pulse;
            SetValueText(S12Find<TextBox>(p + "PulseValue"), $"{pulse} ms");
            S12Find<ToggleButton>(p + "VibrateOnNeutral").IsChecked = fx.VibrateOnNeutral;
            int db = ClampS12Debounce(fx.DebounceMs);
            S12Find<Slider>(p + "DebounceSlider").Value = db;
            SetValueText(S12Find<TextBox>(p + "DebounceValue"), $"{db} ms");
        }

        private static double ClampS12Hz(double v)
            => Math.Max(MozaPedalHapticsProtocol.MinFrequencyHz, Math.Min(MozaPedalHapticsProtocol.MaxFrequencyHz, v));
        private static int ClampS12Pulse(int ms) => (Math.Max(20, Math.Min(1000, ms)) + 5) / 10 * 10;
        private static int ClampS12Debounce(int ms) => (Math.Max(0, Math.Min(1000, ms)) + 25) / 50 * 50;

        // "abs" or "abs:frequency" → channel.
        private static bool TryS12Channel(object? tagObj, out (string Tag, string Cap, PedalHapticsEffectSlot Slot) ch)
        {
            ch = default;
            if (tagObj is not string tag) return false;
            int colon = tag.IndexOf(':');
            string key = colon < 0 ? tag : tag.Substring(0, colon);
            foreach (var c in S12Channels)
                if (c.Tag == key) { ch = c; return true; }
            return false;
        }

        private void UpdateS12Effect(PedalHapticsEffectSlot slot, Action<PedalHapticsEffect> mutate)
        {
            _plugin.UpdateActiveProfile(p => mutate((p.PedalHaptics ??= new PedalHapticsSettings()).For(slot)));
            _plugin.SaveSettings();
        }

        private void S12Enable_Changed(object sender, RoutedEventArgs e)
        {
            if (_suppressEvents) return;
            if (sender is not ToggleButton tog || !TryS12Channel(tog.Tag, out var ch)) return;
            bool on = tog.IsChecked == true;
            UpdateS12Effect(ch.Slot, fx => fx.Enabled = on);
        }

        private void S12Pedal_Changed(object sender, RoutedEventArgs e)
        {
            if (_suppressEvents) return;
            if (sender is not ToggleButton tog || !TryS12Channel(tog.Tag, out var ch)) return;
            bool on = tog.IsChecked == true;
            string pedal = ((string)tog.Tag).Substring(ch.Tag.Length + 1);
            UpdateS12Effect(ch.Slot, fx =>
            {
                if (pedal == "throttle") fx.Throttle = on;
                else if (pedal == "brake") fx.Brake = on;
                else fx.Clutch = on;
            });
        }

        private void S12TriggerMode_Changed(object sender, SelectionChangedEventArgs e)
        {
            if (_suppressEvents) return;
            if (sender is not Selector sel || !TryS12Channel(sel.Tag, out var ch) || sel.SelectedIndex < 0) return;
            var mode = sel.SelectedIndex == 1 ? BaseLfeTriggerMode.OnChange : BaseLfeTriggerMode.Level;
            UpdateS12Effect(ch.Slot, fx => fx.TriggerMode = mode);
            S12Find<FrameworkElement>("S12" + ch.Cap + "EdgeOptions").Visibility =
                mode == BaseLfeTriggerMode.OnChange ? Visibility.Visible : Visibility.Collapsed;
        }

        private void S12Frequency_ValueChanged(object sender, RoutedPropertyChangedEventArgs<double> e)
        {
            if (_suppressEvents) return;
            if (sender is not Slider sl || !TryS12Channel(sl.Tag, out var ch)) return;
            int v = (int)Math.Round(ClampS12Hz(e.NewValue));
            S12Find<TextBox>("S12" + ch.Cap + "FrequencyValue").Text = v.ToString();
            UpdateS12Effect(ch.Slot, fx => fx.Frequency = v);
        }

        private void S12Intensity_ValueChanged(object sender, RoutedPropertyChangedEventArgs<double> e)
        {
            if (_suppressEvents) return;
            if (sender is not Slider sl || !TryS12Channel(sl.Tag, out var ch)) return;
            int v = Math.Max(0, Math.Min(100, (int)Math.Round(e.NewValue)));
            S12Find<TextBox>("S12" + ch.Cap + "IntensityValue").Text = v.ToString();
            UpdateS12Effect(ch.Slot, fx => fx.Intensity = v);
        }

        private void S12Pulse_ValueChanged(object sender, RoutedPropertyChangedEventArgs<double> e)
        {
            if (_suppressEvents) return;
            if (sender is not Slider sl || !TryS12Channel(sl.Tag, out var ch)) return;
            int v = ClampS12Pulse((int)Math.Round(e.NewValue));
            S12Find<TextBox>("S12" + ch.Cap + "PulseValue").Text = $"{v} ms";
            UpdateS12Effect(ch.Slot, fx => fx.PulseMs = v);
        }

        private void S12VibrateOnNeutral_Changed(object sender, RoutedEventArgs e)
        {
            if (_suppressEvents) return;
            if (sender is not ToggleButton tog || !TryS12Channel(tog.Tag, out var ch)) return;
            bool on = tog.IsChecked == true;
            UpdateS12Effect(ch.Slot, fx => fx.VibrateOnNeutral = on);
        }

        private void S12Debounce_ValueChanged(object sender, RoutedPropertyChangedEventArgs<double> e)
        {
            if (_suppressEvents) return;
            if (sender is not Slider sl || !TryS12Channel(sl.Tag, out var ch)) return;
            int v = ClampS12Debounce((int)Math.Round(e.NewValue));
            S12Find<TextBox>("S12" + ch.Cap + "DebounceValue").Text = $"{v} ms";
            UpdateS12Effect(ch.Slot, fx => fx.DebounceMs = v);
        }

        private void S12FreqRange_RangeChanged(object sender, EventArgs e)
        {
            if (_suppressEvents) return;
            if (sender is not MozaControls.MozaRangeSlider rs || !TryS12Channel(rs.Tag, out var ch)) return;
            float lo = (float)ClampS12Hz(rs.LowValue), hi = (float)ClampS12Hz(rs.HighValue);
            S12Find<TextBlock>("S12" + ch.Cap + "FreqRangeText").Text = LfeRangeText(lo, hi);
            UpdateS12Effect(ch.Slot, fx => { fx.FrequencyMin = lo; fx.FrequencyMax = hi; });
        }

        private void S12Test_Click(object sender, RoutedEventArgs e)
        {
            if (!TryS12Channel((sender as FrameworkElement)?.Tag, out var ch)) return;
            _plugin.TriggerPedalHapticsTest(ch.Slot);
        }

        // Every enabled card's test at once — the combined feel of the setup.
        private void S12TestAll_Click(object sender, RoutedEventArgs e)
        {
            var settings = _plugin.Settings?.ProfileStore?.CurrentProfile?.PedalHaptics ?? new PedalHapticsSettings();
            foreach (var (_, _, slot) in S12Channels)
                if (settings.Get(slot).Enabled) _plugin.TriggerPedalHapticsTest(slot);
        }

        // ƒₓ — SimHub's formula editor for the tagged "channel:param" field. An
        // empty result clears back to the slider.
        private async void S12Fx_Click(object sender, RoutedEventArgs e)
        {
            if ((sender as FrameworkElement)?.Tag is not string tag || !TryS12Channel(tag, out var ch)) return;
            string param = tag.Substring(tag.IndexOf(':') + 1);
            var engine = _plugin.ChannelFormulaEngine;
            if (engine == null)
            {
                MozaLog.Warn("[AZOM] S12 formula editor unavailable (SimHub engine not loaded)");
                return;
            }
            var fx = (_plugin.Settings?.ProfileStore?.CurrentProfile?.PedalHaptics ?? new PedalHapticsSettings()).Get(ch.Slot);
            var ev = LfeMakeExpression(GetS12Formula(fx, param));
            var working = new ExpressionValue { UseJavascript = ev.UseJavascript, Expression = ev.Expression, PreExpression = ev.PreExpression };
            var data = new DashboardBindingData
            {
                Formula = working,
                Mode = string.IsNullOrWhiteSpace(working.Expression) ? BindingMode.None : BindingMode.Formula,
                TargetPropertyName = tag,
                TargetType = typeof(double),
            };
            try
            {
                var editor = new BindingEditor(engine) { DataContext = data };
                var result = await editor.ShowDialogWindowAsync(this);
                if ((int)result != 1) return;
                string formula = data.Mode == BindingMode.Formula ? LfeSerializeExpression(data.Formula) : "";
                UpdateS12Effect(ch.Slot, f => SetS12Formula(f, param, formula));
                RefreshDisplay(this, EventArgs.Empty);
            }
            catch (Exception ex) { MozaLog.Warn("[AZOM] S12 formula editor failed: " + ex.Message); }
        }

        private static string GetS12Formula(PedalHapticsEffect fx, string param) => param switch
        {
            "trigger" => fx.TriggerFormula,
            "frequency" => fx.FrequencyFormula,
            _ => fx.IntensityFormula,
        };

        private static void SetS12Formula(PedalHapticsEffect fx, string param, string formula)
        {
            if (param == "trigger") fx.TriggerFormula = formula;
            else if (param == "frequency") fx.FrequencyFormula = formula;
            else fx.IntensityFormula = formula;
        }
    }
